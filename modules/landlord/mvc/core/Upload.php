<?php
declare(strict_types=1);
/**
 * Handles Landlord uploads with readable, collision-resistant server filenames.
 *
 * Format: property_000012_20261018_1a2b3c4d5e6f7a8b.jpg
 * - The category tells maintainers what kind of file it is.
 * - The optional numeric identifier identifies an owned entity, not a person.
 * - The YYYYMMDD segment records when the server stored the file.
 * - The random suffix prevents collisions and guessing predictable paths.
 * - An untrusted client filename is NEVER used as a disk path.
 *
 * Legacy 40-hex-character uploads are still readable/removable. This edition
 * DOES NOT change existing file paths, database columns or gallery seed images.
 */
namespace BoardNest\Core;
final class Upload {
    private const PUBLIC_CATEGORIES = ['properties'=>'property', 'rooms'=>'room', 'avatars'=>'avatar'];
    private const PRIVATE_CATEGORIES = ['nic'=>'nic', 'complaints'=>'complaint'];

    private static function checked(array $file,int $max,array $allowed): string {
        if(($file['error']??UPLOAD_ERR_NO_FILE)!==UPLOAD_ERR_OK) throw new \DomainException('Please choose a valid file.');
        if(($file['size']??0)<1||$file['size']>$max) throw new \DomainException('File is empty or larger than 5 MB.');
        if(!isset($file['tmp_name'])||!is_uploaded_file($file['tmp_name'])) throw new \DomainException('Invalid upload.');
        $mime=(new \finfo(FILEINFO_MIME_TYPE))->file($file['tmp_name']);
        if(!isset($allowed[$mime])) throw new \DomainException('Unsupported file type.');
        if(str_starts_with($mime,'image/')&&@getimagesize($file['tmp_name'])===false) throw new \DomainException('Invalid image.');
        if($mime==='application/pdf'&&file_get_contents($file['tmp_name'],false,null,0,5)!=='%PDF-') throw new \DomainException('Invalid PDF document.');
        return $allowed[$mime];
    }

    /** Sensitive documents stay outside the public Apache DocumentRoot. */
    private static function privateRoot(): string {
        $project=dirname(__DIR__,4);
        $suffix=substr(hash('sha256',$project),0,16);
        $docRoot=realpath((string)($_SERVER['DOCUMENT_ROOT']??''));
        if(is_string($docRoot)&&$docRoot!=='') return dirname($docRoot).'/boardnest_private_'.$suffix;
        return rtrim(sys_get_temp_dir(),'/\\').'/boardnest_private_'.$suffix;
    }

    /**
     * Match only filenames generated by this server, or the previous hex format.
     * Folder + extension checks prevent path traversal on delete/download.
     */
    private static function acceptable(string $filename,string $folder,bool $private): bool {
        $exts=$private?'(?:jpg|png|pdf)':'(?:jpg|png|webp)';
        $prefix=$private?(self::PRIVATE_CATEGORIES[$folder]??null):(self::PUBLIC_CATEGORIES[$folder]??null);
        if($prefix===null) return false;
        $legacy='[a-f0-9]{40}\.'.$exts;
        $readable=preg_quote($prefix,'~').'(?:_[0-9]{1,9})?_[0-9]{8}_[a-f0-9]{16}\.'.$exts;
        return (bool)preg_match('~^(?:'.$readable.'|'.$legacy.')$~D',$filename);
    }

    /** Convert a private logical DB path into a disk path; never trust arbitrary paths. */
    public static function privateFilePath(string $relative): ?string {
        if(!preg_match('~^storage/private/(nic|complaints)/([^/]+)$~D',$relative,$m)) return null;
        if(!self::acceptable($m[2],$m[1],true)) return null;
        return self::privateRoot().'/'.$m[1].'/'.$m[2];
    }

    /**
     * Save an actual HTTP upload. Context ID is the owning property/room/landlord/booking.
     * It is accepted only when positive and is formatted to at most nine digits.
     * Clients cannot supply their own storage filename.
     */
    public static function save(array $file,string $folder,bool $private=false,int $contextId=0): string {
        if($private&&!isset(self::PRIVATE_CATEGORIES[$folder])) throw new \LogicException('Invalid private upload category.');
        if(!$private&&!isset(self::PUBLIC_CATEGORIES[$folder])) throw new \LogicException('Invalid public upload category.');
        if($contextId<0||$contextId>999999999) throw new \InvalidArgumentException('Invalid upload context ID.');
        $formats=$private
            ? ['image/jpeg'=>'jpg','image/png'=>'png','application/pdf'=>'pdf']
            : ['image/jpeg'=>'jpg','image/png'=>'png','image/webp'=>'webp'];
        $ext=self::checked($file,5*1024*1024,$formats);
        $folderOnDisk=$private
            ? self::privateRoot().'/'.$folder
            : dirname(__DIR__,4).'/public/landlord/assets/uploads/landlord/'.$folder;
        if(!is_dir($folderOnDisk)&&!mkdir($folderOnDisk,0750,true)&&!is_dir($folderOnDisk)) throw new \RuntimeException('Upload storage unavailable.');
        $prefix=$private?self::PRIVATE_CATEGORIES[$folder]:self::PUBLIC_CATEGORIES[$folder];
        $part=$contextId>0?'_'.str_pad((string)$contextId,6,'0',STR_PAD_LEFT):'';
        $filename=$prefix.$part.'_'.gmdate('Ymd').'_'.bin2hex(random_bytes(8)).'.'.$ext;
        // move_uploaded_file() refuses overwrites in normal operation because the
        // random suffix makes a collision vanishingly unlikely. Explicit guard too.
        for($i=0;$i<3&&is_file($folderOnDisk.'/'.$filename);$i++){
            $filename=$prefix.$part.'_'.gmdate('Ymd').'_'.bin2hex(random_bytes(8)).'.'.$ext;
        }
        if(is_file($folderOnDisk.'/'.$filename)) throw new \RuntimeException('Upload filename collision.');
        if(!move_uploaded_file($file['tmp_name'],$folderOnDisk.'/'.$filename)) throw new \RuntimeException('Unable to save upload.');
        return $private
            ? 'storage/private/'.$folder.'/'.$filename
            : 'assets/uploads/landlord/'.$folder.'/'.$filename;
    }

    /** Delete a file created by this application (both old and new naming). */
    public static function delete(string $path,bool $private=false): void {
        if($private){
            $disk=self::privateFilePath($path);
        }else{
            $disk=null;
            if(preg_match('~^assets/uploads/landlord/(properties|rooms|avatars)/([^/]+)$~D',$path,$m)
                &&self::acceptable($m[2],$m[1],false)){
                $disk=dirname(__DIR__,4).'/public/landlord/'.$path;
            }
        }
        if(is_string($disk)&&is_file($disk)) @unlink($disk);
    }
}
